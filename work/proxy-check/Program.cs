using System.Net;
using System.Net.Http.Json;
using System.Net.WebSockets;
using System.Text.Json;
if(args.Length!=3)throw new ArgumentException("Usage: secrets.json Versionskennung.json https://game.example.org");
var origin=args[2].TrimEnd('/');
var api=origin+"/env/prod/contract/1";
using var secret=JsonDocument.Parse(File.ReadAllText(args[0]));
using var version=JsonDocument.Parse(File.ReadAllText(args[1]));
using var http=new HttpClient{Timeout=TimeSpan.FromSeconds(15)};
using var check=await http.PostAsJsonAsync(api+"/VersionCheck",new {execrc=version.RootElement.GetProperty("NativeClientCRC32").GetUInt32(),ver=1,netver=1,servicesver=1});
check.EnsureSuccessStatusCode();
using var result=JsonDocument.Parse(await check.Content.ReadAsStringAsync());
if(result.RootElement.GetProperty("result").GetInt32()!=0)throw new Exception("Version rejected");
Console.WriteLine("PASS: public HTTPS with trusted TLS certificate; release version accepted");
using var denied=await http.PostAsJsonAsync(api+"/GuestSession",new {display_name="ProxyInvalid",invitation="deliberately-invalid-invitation"});
if(denied.StatusCode!=HttpStatusCode.Unauthorized)throw new Exception("Invalid invitation not rejected");
using var noAuth=await http.GetAsync(api+"/ws");
if(noAuth.StatusCode!=HttpStatusCode.Unauthorized)throw new Exception("Unauthenticated WebSocket endpoint not rejected");
Console.WriteLine("PASS: invalid invitation and unauthenticated WebSocket request rejected (401)");
using var login=await http.PostAsJsonAsync(api+"/GuestSession",new {display_name="ProxyTest"+DateTime.UtcNow.ToString("HHmmss"),invitation=secret.RootElement.GetProperty("invitation").GetString()});
login.EnsureSuccessStatusCode();
using var session=JsonDocument.Parse(await login.Content.ReadAsStringAsync());
var wsUri=session.RootElement.GetProperty("ws_uri").GetString();
if(wsUri!=origin.Replace("https://","wss://")+"/env/prod/contract/1/ws")throw new Exception("Unexpected WebSocket URL");
Console.WriteLine("PASS: invited guest login; server returns public WSS URL");
using var ws=new ClientWebSocket();
ws.Options.SetRequestHeader("Authorization","Bearer "+session.RootElement.GetProperty("session_token").GetString());
using var deadline=new CancellationTokenSource(TimeSpan.FromSeconds(20));
await ws.ConnectAsync(new Uri(wsUri),deadline.Token);
if(ws.State!=WebSocketState.Open)throw new Exception("WebSocket not open");
var bytes=new byte[65536];
var message=await ws.ReceiveAsync(bytes.AsMemory(),deadline.Token);
if(message.MessageType==WebSocketMessageType.Close||message.Count==0)throw new Exception("No server data received");
Console.WriteLine("PASS: authenticated WSS upgrade and lobby server event received through Synology");
await ws.CloseAsync(WebSocketCloseStatus.NormalClosure,"Proxy check completed",deadline.Token);
Console.WriteLine("PASS: clean WebSocket close");
